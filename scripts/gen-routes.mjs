// Generates components/pages/<Name>Page.tsx (client: logic + view) and app/<route>/page.tsx
// for every page in the registry. Run as part of: npm run convert
import fs from 'node:fs';
import path from 'node:path';
import { PAGES } from './pages.mjs';

const TITLES = {
  Home: ['Superchat: get two hours of your day back', 'Superchat is the UAE AI assistant that completes tasks through chat: send money abroad, book flights and restaurants, pay bills and manage your calendar.'],
  WhatsApp: ['Superchat on WhatsApp', 'The same Superchat agent, right inside the WhatsApp chats you already use.'],
  BlogHub: ['Blog', 'Guides on money, travel, bookings, shopping and everyday life in the UAE.'],
  Security: ['Security', 'How Superchat keeps your money, data and conversations safe.'],
  Contact: ['Contact', 'Talk to the Superchat team.'],
  Money: ['Money', 'Send at the Google rate, pay bills in one message and see where every dirham goes.'],
  MoneySendMoney: ['Send money', 'Send money home at the Google rate, delivered in minutes.'],
  MoneyWallet: ['Wallet', 'Pay bills and check balances in chat.'],
  MoneyExpenses: ['Expenses', 'Duplicates flagged, spend less.'],
  Travel: ['Travel', 'Flights, stays and trips found, compared and booked in one chat.'],
  TravelFlightBooking: ['Flight booking', 'Found, compared, booked in one chat.'],
  TravelHotelBooking: ['Hotel booking', 'The right room, without the tabs.'],
  TravelTripPlanner: ['Trip planner', 'Flights, stays and plans sorted.'],
  Bookings: ['Bookings', 'Tables, parking, rentals and home services, booked for you.'],
  BookingsRestaurants: ['Restaurants', 'Tables booked, even on busy nights.'],
  BookingsParkingRentals: ['Parking & rentals', 'Park or rent a car by typing.'],
  BookingsHomeServices: ['Home services', 'Cleaning and repairs, handled.'],
  Shopping: ['Shopping', 'Find anything, get the better deal and order from your favourite stores.'],
  ShoppingProductSearch: ['Product search', 'Find anything with text or a photo.'],
  ShoppingAIShopping: ['AI shopping', 'Always the better deal.'],
  ShoppingAIOrdering: ['AI ordering', 'Order from your favourite stores.'],
  Everyday: ['Everyday', 'Smart chat, reminders, email and calendar on autopilot.'],
  EverydaySmartChat: ['Smart chat', 'Your dependable personal assistant.'],
  EverydayReminders: ['Reminders', 'A nudge before anything is due.'],
  EverydayEmailCalendar: ['Email & calendar', 'Inbox and schedule, handled.'],
};
for (const v of ['Money', 'Travel', 'Bookings', 'Shopping', 'Everyday']) TITLES[v + 'Blog'] = [`${v} blog`, `Guides and tips from Superchat on ${v.toLowerCase()}.`];

const w = (f, s) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s); };
const HEAD = '// GENERATED by scripts/gen-routes.mjs. Do not edit by hand.\n';

for (const p of PAGES) {
  const extra = p.kind === 'article' ? 'slug' : p.kind === 'legal' ? 'doc' : null;
  w(`components/pages/${p.name}Page.tsx`, `${HEAD}'use client';
import ${p.name}View from '@/components/views/${p.name}View';
import { useLogic } from '@/lib/dc';
import ${p.name}Logic, { DEFAULT_PROPS } from '@/lib/logic/${p.name}.logic';

export default function ${p.name}Page(${extra ? `{ ${extra} }: { ${extra}: string }` : ''}) {
  const v = useLogic(${p.name}Logic, { ...DEFAULT_PROPS${extra ? `, ${extra}` : ''} });
  return <${p.name}View v={v} />;
}
`);
  const dir = p.route === '/' ? 'app' : 'app' + p.route;
  if (p.kind === 'article') {
    const mod = p.content.replace(/\.js$/, '');
    w(`${dir}/page.tsx`, `${HEAD}import type { Metadata } from 'next';
import { notFound } from 'next/navigation';
import ${p.name}Page from '@/components/pages/${p.name}Page';
import { POSTS } from '@/content/${mod}';

export const dynamicParams = false;
export function generateStaticParams() {
  return (POSTS as any[]).map((x) => ({ slug: x.slug }));
}
export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  const post = (POSTS as any[]).find((x) => x.slug === slug);
  return post ? { title: post.title, description: post.dek } : {};
}
export default async function Page({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  if (!(POSTS as any[]).some((x) => x.slug === slug)) notFound();
  return <${p.name}Page slug={slug} />;
}
`);
  } else if (p.kind === 'legal') {
    for (const [route, doc, title] of [['/privacy-policy', 'privacy', 'Privacy Policy'], ['/terms-of-use', 'terms', 'Terms of Use']]) {
      w(`app${route}/page.tsx`, `${HEAD}import type { Metadata } from 'next';
import ${p.name}Page from '@/components/pages/${p.name}Page';

export const metadata: Metadata = { title: '${title}' };

export default function Page() {
  return <${p.name}Page doc="${doc}" />;
}
`);
    }
  } else {
    const [t, d] = TITLES[p.name] || [p.name, ''];
    w(`${dir}/page.tsx`, `${HEAD}import type { Metadata } from 'next';
import ${p.name}Page from '@/components/pages/${p.name}Page';

export const metadata: Metadata = ${p.name === 'Home' ? `{ title: { absolute: ${JSON.stringify(t)} }, description: ${JSON.stringify(d)} }` : `{ title: ${JSON.stringify(t)}, description: ${JSON.stringify(d)} }`};

export default function Page() {
  return <${p.name}Page />;
}
`);
  }
}

// sitemap.ts
const statics = PAGES.filter((p) => !p.kind).map((p) => p.route).concat(['/privacy-policy', '/terms-of-use']);
const arts = PAGES.filter((p) => p.kind === 'article');
w('app/sitemap.ts', `${HEAD}import type { MetadataRoute } from 'next';
${arts.map((a) => `import { POSTS as ${a.name}Posts } from '@/content/${a.content.replace(/\.js$/, '')}';`).join('\n')}

const BASE = 'https://superchat-site-v4.vercel.app';
export default function sitemap(): MetadataRoute.Sitemap {
  const routes = ${JSON.stringify(statics)};
  const posts: string[] = [
${arts.map((a) => `    ...(${a.name}Posts as any[]).map((x) => '${a.route.replace('[slug]', '')}' + x.slug),`).join('\n')}
  ];
  return [...routes, ...posts].map((r) => ({ url: BASE + r }));
}
`);
w('app/robots.ts', `${HEAD}import type { MetadataRoute } from 'next';

export default function robots(): MetadataRoute.Robots {
  return { rules: { userAgent: '*', allow: '/' }, sitemap: 'https://superchat-site-v4.vercel.app/sitemap.xml' };
}
`);
